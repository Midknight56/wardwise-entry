import assert from 'node:assert/strict';
import cityJson from '../../public/data/chicago.json';
import type { CityData } from '../../src/model/types';
import { allocate } from '../../src/model/allocate';
import { compareWards, checkAnswer } from '../../src/model/explain';
import { ask, type AskDependencies } from '../../src/server/ai/ask';
import { world } from './world';
const city = cityJson as unknown as CityData;
const plan = allocate(5000, 'y2023', city.wards);
assert.equal(Object.values(plan.perWard).reduce((sum, amount) => sum + amount, 0), 5000);
const from = Number(Object.keys(plan.perWard).find(id => plan.perWard[Number(id)] >= 350));
const to = city.wards.find(w => w.id !== from)!.id;
const w = world(plan.perWard);
let calls = 0;
const deps: AskDependencies = { wards: city.wards, gate: w.gate, ledger: { reserve: async () => 1, settle: async () => {} }, ai: { run: async () => { calls++; return { response: `Ward ${from} gets $${plan.perWard[from]}.` }; } }, live: false };
const question = { kind: 'why' as const, a: from, b: to, budget: 5000 };
const rules = await ask(question, deps);
assert.equal(rules.source, 'rules');
assert.equal(checkAnswer(rules.text, compareWards(from, to, plan, 'y2023', city.wards), [from, to]).ok, true);
const move = await ask({ kind: 'move', from, to, amount: 50, budget: 5000 }, deps);
assert.equal(move.source, 'rules'); assert.match(move.text, /Moving \$/);
deps.live = true;
assert.equal((await ask(question, deps)).source, 'live');
assert.equal((await ask(question, deps)).source, 'cache'); assert.equal(calls, 1);
deps.ai.run = async () => ({ response: 'Ward 99 receives $999999.' });
assert.equal((await ask({ ...question, budget: 5050 }, deps)).source, 'rules');
const money = new (await import('../../src/server/campaign/engine')).CampaignEngine({ ...w.options, wards: city.wards.map(w => w.id), plan: plan.perWard });
const log = await money.createWorklog({ ward: from, payee: 'crew-north', units: 100 });
assert.equal((await money.pay(log.id)).status, 'SUCCESS');
console.log(`Real ${city.wards.length}-ward data: $5000 allocation, why/move templates, checked live/cache/rules paths, and plan-backed payout passed.`);
